#![cfg(feature = "native")]

use std::{path::PathBuf, sync::Arc};
use taiyou_render::renderer::*;

fn catalog() -> Arc<ValidatedFontCatalog> {
    let limits = Limits::default();
    let mut context = FontContext::with_limits(limits.clone()).unwrap();
    let mut builder = FontCatalogBuilder::new(limits);
    let path =
        PathBuf::from(std::env::var("RUNNER_TEMP").unwrap()).join("taiyou-shaping-fonts/latin.otf");
    builder
        .register(&mut context, &std::fs::read(path).unwrap(), 0)
        .unwrap();
    builder.snapshot(&mut CatalogIngestor::new()).unwrap()
}
fn source(scaled: bool, text: &str) -> String {
    // Intentionally retain the pre-T016 format without BackColour. Its opaque
    // shadow paint is tested with explicit positive depth below one Q6 tick.
    format!(
        "[Script Info]\nPlayResX: 160\nPlayResY: 100\nWrapStyle: 2\nScaledBorderAndShadow: {}\n[V4+ Styles]\nFormat: Name,Fontname,Fontsize,PrimaryColour,Outline,Shadow,Alignment,MarginL,MarginR,MarginV\nStyle: Default,Source Sans 3,20,&H00FFFFFF,0,0,7,10,10,10\n[Events]\nFormat: Layer,Start,End,Style,Text\nDialogue: 0,0:00:00.10,0:00:01.00,Default,{text}",
        if scaled { "yes" } else { "no" }
    )
}
fn render(
    source: &str,
    fonts: Arc<ValidatedFontCatalog>,
    limits: Limits,
    size: Size,
) -> Result<Frame, RenderError> {
    let track = taiyou_ass::parse_ass(
        source.as_bytes(),
        &ParseOptions::new(
            InputEncoding::Utf8,
            Profile::CoreV1,
            Limits::default(),
            SyntaxPolicy::Strict,
        ),
        &mut TrackIngestor::new(),
    )
    .unwrap()
    .track()
    .clone();
    Renderer::new(RendererConfig {
        workers: std::num::NonZeroUsize::new(1).unwrap(),
        profile: Profile::CoreV1,
        limits,
        cache: CacheConfig::Disabled,
    })
    .unwrap()
    .render(
        track,
        fonts,
        &RenderRequest {
            now: TimeUs::from_micros(500_000),
            viewport: Viewport::full(size).unwrap(),
            unsupported: UnsupportedPolicy::Strict,
        },
    )
}
fn ordinary(source: &str, fonts: Arc<ValidatedFontCatalog>, size: Size) -> Frame {
    render(source, fonts, Limits::default(), size).unwrap()
}
fn mul(a: u8, b: u8) -> u8 {
    ((u32::from(a) * u32::from(b) + 127) / 255) as u8
}
fn over(dst: &mut [u8], coverage: u8, color: [u8; 4]) {
    let a = mul(coverage, color[3]);
    let inverse = 256 - u32::from(a);
    for i in 0..3 {
        dst[i] =
            ((u32::from(dst[i]) * inverse + u32::from(color[i]) * (u32::from(a) + 1)) >> 8) as u8;
    }
    dst[3] = 255 - (((255 - u32::from(dst[3])) * inverse) >> 8) as u8;
}

#[test]
fn prior_fill_reference_and_positive_coincident_shadow_are_independently_preserved() {
    let fonts = catalog();
    let size = Size::new(160, 100);
    for alignment in 1..=9 {
        let opaque_fill = ordinary(
            &source(false, &format!("{{\\an{alignment}\\4a&HFF&}}H")),
            fonts.clone(),
            size,
        );
        let mask: Vec<_> = opaque_fill.pixels().chunks_exact(4).map(|p| p[3]).collect();
        if let Some(folder) = std::env::var_os("TAIYOU_RENDER_REFERENCE_DIR") {
            // Existing independent C/FreeType H reference, never regenerated by
            // this test. The production fill path must still match every byte.
            let independent =
                std::fs::read(PathBuf::from(folder).join(format!("align{alignment}.a8"))).unwrap();
            assert_eq!(mask, independent);
        }
        let fill_only = ordinary(
            &source(
                false,
                &format!("{{\\an{alignment}\\1c&H2850C8&\\alpha&H7F&\\4a&HFF&}}H"),
            ),
            fonts.clone(),
            size,
        );
        let visible_default = ordinary(
            &source(
                false,
                &format!("{{\\an{alignment}\\1c&H2850C8&\\alpha&H7F&\\shad0.001}}H"),
            ),
            fonts.clone(),
            size,
        );
        let mut expected_fill = vec![0; mask.len() * 4];
        let mut expected_effect = expected_fill.clone();
        for (i, &coverage) in mask.iter().enumerate() {
            over(
                &mut expected_fill[i * 4..i * 4 + 4],
                coverage,
                [200, 80, 40, 128],
            );
            over(
                &mut expected_effect[i * 4..i * 4 + 4],
                coverage,
                [0, 0, 0, 128],
            );
            over(
                &mut expected_effect[i * 4..i * 4 + 4],
                coverage,
                [200, 80, 40, 128],
            );
        }
        assert_eq!(
            fill_only.pixels(),
            expected_fill,
            "fill alignment {alignment}"
        );
        assert_eq!(
            visible_default.pixels(),
            expected_effect,
            "positive coincident shadow {alignment}"
        );
        assert_ne!(visible_default.pixels(), fill_only.pixels());
    }
}

#[test]
fn transparent_shadow_needs_no_offset_raster_or_additional_segment_budget() {
    let fonts = catalog();
    let size = Size::new(160, 100);
    let zero = source(false, r"{\bord1\shad0\4a&HFF&}H");
    // Find the smallest successful frame segment budget. A transparent pass at
    // any offset must fit that same budget and preserve all pixels.
    let (mut low, mut high) = (1, 4096);
    while low < high {
        let mid = (low + high) / 2;
        let limits = Limits::default().with_path_segments_per_frame(mid).unwrap();
        match render(&zero, fonts.clone(), limits, size) {
            Ok(_) => high = mid,
            Err(e) => {
                assert_eq!(e.code(), ErrorCode::LimitExceeded);
                low = mid + 1;
            }
        }
    }
    let limits = Limits::default()
        .with_path_segments_per_frame(high)
        .unwrap();
    let baseline = render(&zero, fonts.clone(), limits.clone(), size).unwrap();
    for offset in ["0.5", "-1.25", "1000000000"] {
        let invisible = source(false, &format!("{{\\bord1\\shad{offset}\\4a&HFF&}}H"));
        let actual = render(&invisible, fonts.clone(), limits.clone(), size).unwrap();
        assert_eq!(actual.pixels(), baseline.pixels());
    }
    let visible = ordinary(&source(false, r"{\bord1\shad3\4a&H00&}H"), fonts, size);
    assert_ne!(visible.pixels(), baseline.pixels());
}

#[test]
fn positive_shadow_quantized_to_zero_offset_preserves_faded_fill_behavior() {
    let fonts = catalog();
    let size = Size::new(160, 100);
    let shadow = ordinary(
        // A nonzero original fill rounds to zero after fade, but still casts
        // a filled shadow. An originally transparent, unbordered fill does not.
        &source(
            false,
            r"{\bord0\shad0.001\1a&HFE&\4c&HFF0000&\4a&H00&\fade(128,128,128,0,0,1000,1000)}H",
        ),
        fonts.clone(),
        size,
    );
    let fill = ordinary(
        &source(false, r"{\bord0\1c&HFF0000&\1a&H80&\4a&HFF&}H"),
        fonts,
        size,
    );
    assert_eq!(shadow.pixels(), fill.pixels());
    assert!(shadow.pixels().iter().any(|&v| v != 0));
}

#[test]
fn shadow_and_border_sbas_only_scale_effect_parameters_when_enabled() {
    let fonts = catalog();
    let size = Size::new(320, 200);
    for (no_tags, yes_tags) in [
        (
            r"{\bord2\shad0\4a&HFF&\1a&HFF&}H",
            r"{\bord1\shad0\4a&HFF&\1a&HFF&}H",
        ),
        (
            r"{\bord0\shad2\1a&HFF&\2a&HFF&\kf100\4a&H00&}H",
            r"{\bord0\shad1\1a&HFF&\2a&HFF&\kf100\4a&H00&}H",
        ),
        (
            r"{\bord0\shad0.5\1a&HFF&\2a&HFF&\kf100\4a&H00&}H",
            r"{\bord0\shad0.25\1a&HFF&\2a&HFF&\kf100\4a&H00&}H",
        ),
    ] {
        let no = ordinary(&source(false, no_tags), fonts.clone(), size);
        let yes = ordinary(&source(true, yes_tags), fonts.clone(), size);
        assert_eq!(no.pixels(), yes.pixels(), "{no_tags}");
    }
    // Unequal x/y ratios: shadow scales independently, even while isotropic
    // border expansion with unequal axes remains unsupported.
    let size = Size::new(320, 300);
    let zero_tags = r"{\bord0\shad0\1c&H000000&\1a&H00&\4a&HFF&}H";
    let tags = r"{\bord0\shad1\1a&HFF&\2a&HFF&\kf100\4a&H00&}H";
    let base = ordinary(&source(false, zero_tags), fonts.clone(), size);
    for (scaled, dx, dy) in [(false, 1usize, 1usize), (true, 2, 3)] {
        let actual = ordinary(&source(scaled, tags), fonts.clone(), size);
        let mut expected = vec![0; actual.pixels().len()];
        for y in dy..300 {
            for x in dx..320 {
                let dst = (y * 320 + x) * 4;
                let src = ((y - dy) * 320 + x - dx) * 4;
                expected[dst..dst + 4].copy_from_slice(&base.pixels()[src..src + 4]);
            }
        }
        assert_eq!(actual.pixels(), expected, "SBAS={scaled}");
    }
}

#[test]
fn prior_layer_order_keeps_positive_shadows_and_fill_coverage() {
    let fonts = catalog();
    let size = Size::new(160, 100);
    let pure = ordinary(&source(false, r"{\4a&HFF&}H"), fonts.clone(), size);
    let mask: Vec<_> = pure.pixels().chunks_exact(4).map(|p| p[3]).collect();
    let header = source(false, "")
        .split("[Events]")
        .next()
        .unwrap()
        .to_owned();
    let input = format!(
        "{header}[Events]\nFormat: Layer,Start,End,Style,Text\nDialogue: 1,0:00:00.10,0:00:01.00,Default,{{\\pos(10,10)\\shad0.001\\1c&HFF0000&}}H\nDialogue: -1,0:00:00.10,0:00:01.00,Default,{{\\pos(10,10)\\shad0.001\\1c&H0000FF&\\alpha&H7F&}}H"
    );
    for (input, front_blue) in [
        (&input, true),
        (&input.replace("Dialogue: 1,", "Dialogue: -1,"), false),
    ] {
        let actual = ordinary(input, fonts.clone(), size);
        let mut expected = vec![0; mask.len() * 4];
        for (i, &coverage) in mask.iter().enumerate() {
            let pixel = &mut expected[i * 4..i * 4 + 4];
            let passes = if front_blue {
                [
                    [0, 0, 0, 128],
                    [255, 0, 0, 128],
                    [0, 0, 0, 255],
                    [0, 0, 255, 255],
                ]
            } else {
                [
                    [0, 0, 0, 255],
                    [0, 0, 255, 255],
                    [0, 0, 0, 128],
                    [255, 0, 0, 128],
                ]
            };
            for paint in passes {
                over(pixel, coverage, paint);
            }
        }
        assert_eq!(actual.pixels(), expected, "front blue={front_blue}");
    }
}
